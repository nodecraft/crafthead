//! Static snapshots of cosmetic particle systems.
//!
//! Avatars are single frames, so each spawner is posed at the moment its particles are most
//! visible: the middle of the longest full-opacity stretch of its animation.

use crate::asset_provider::AssetProvider;
use crate::cosmetic_attachment::find_node_by_name;
use crate::scene::SceneNode;
use crate::texture::Texture;
use glam::{Mat4, Vec2, Vec3};
use serde::Deserialize;
use std::collections::HashMap;
use std::sync::Arc;

/// Particle offsets and scales are in blocks; blockymodels are authored at 64 units per block.
pub const UNITS_PER_BLOCK: f32 = 64.0;

/// Path of the manifest generated by `scripts/extract-hytale-assets.ts`, relative to the asset root.
pub const MANIFEST_PATH: &str = "Particles/CosmeticParticles.json";

#[derive(Debug, Clone, Copy, Default, Deserialize)]
#[serde(rename_all = "PascalCase", default)]
pub struct PartialVec3 {
	pub x: f32,
	pub y: f32,
	pub z: f32,
}

impl From<PartialVec3> for Vec3 {
	fn from(v: PartialVec3) -> Self {
		Vec3::new(v.x, v.y, v.z)
	}
}

/// Particle system attached to a cosmetic (`Particles` entries in CharacterCreator JSON)
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub struct ModelParticle {
	pub system_id: String,
	pub target_node_name: Option<String>,
	#[serde(default)]
	pub position_offset: PartialVec3,
	pub scale: Option<f32>,
}

#[derive(Debug, Clone, Default, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub struct ParticleManifest {
	pub systems: HashMap<String, ParticleSystem>,
	pub spawners: HashMap<String, ParticleSpawner>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub struct ParticleSystem {
	#[serde(default)]
	pub spawners: Vec<SpawnerGroup>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub struct SpawnerGroup {
	pub spawner_id: String,
	#[serde(default)]
	pub position_offset: PartialVec3,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub struct ParticleSpawner {
	pub max_concurrent_particles: Option<u32>,
	pub particle_rotation_influence: Option<String>,
	pub particle_life_span: Option<Range>,
	#[serde(default)]
	pub emit_offset: RangeVec3,
	#[serde(default)]
	pub attractors: Vec<ParticleAttractor>,
	pub particle: ParticleDefinition,
}

#[derive(Debug, Clone, Copy, Default, Deserialize)]
#[serde(rename_all = "PascalCase", default)]
pub struct ParticleAttractor {
	pub radius: Option<f32>,
	pub radial_acceleration: f32,
	pub radial_tangent_acceleration: f32,
	pub linear_acceleration: PartialVec3,
}

#[derive(Debug, Clone, Copy, Default, Deserialize)]
#[serde(rename_all = "PascalCase", default)]
pub struct Range {
	pub min: f32,
	pub max: f32,
}

impl Range {
	fn lerp(self, t: f32) -> f32 {
		self.min + (self.max - self.min) * t
	}
}

#[derive(Debug, Clone, Copy, Default, Deserialize)]
#[serde(rename_all = "PascalCase", default)]
pub struct RangeVec3 {
	pub x: Option<Range>,
	pub y: Option<Range>,
	pub z: Option<Range>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub struct ParticleDefinition {
	pub texture: String,
	pub frame_size: Option<FrameSize>,
	pub scale_ratio_constraint: Option<String>,
	/// Keyed by percentage of the particle's lifetime ("0".."100")
	#[serde(default)]
	pub animation: HashMap<String, AnimationFrame>,
	#[serde(default)]
	pub initial_animation_frame: AnimationFrame,
}

#[derive(Debug, Clone, Copy, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub struct FrameSize {
	pub width: u32,
	pub height: u32,
}

#[derive(Debug, Clone, Default, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub struct AnimationFrame {
	pub opacity: Option<f32>,
	pub color: Option<String>,
	pub frame_index: Option<Range>,
	pub scale: Option<ScaleRange>,
}

#[derive(Debug, Clone, Copy, Default, Deserialize)]
#[serde(rename_all = "PascalCase", default)]
pub struct ScaleRange {
	pub x: Option<Range>,
	pub y: Option<Range>,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum SpriteFacing {
	/// Faces the camera fully
	Camera,
	/// Stays vertical and turns only around the world Y axis, like a velocity billboard rising straight up
	Upright,
}

/// A textured quad posed in model space
#[derive(Debug, Clone)]
pub struct ParticleSprite {
	pub center: Vec3,
	/// Quad size in model units; a negative axis mirrors the texture along it
	pub size: Vec2,
	pub facing: SpriteFacing,
	/// RGB multiplier and opacity
	pub color: [f32; 4],
	pub texture: Arc<Texture>,
	/// Frame rectangle in texture pixels: (x, y, width, height)
	pub frame: (u32, u32, u32, u32),
}

/// Build sprites for every particle system attached to a cosmetic
pub fn snapshot(
	particles: &[ModelParticle],
	manifest: &ParticleManifest,
	nodes: &[SceneNode],
	asset_provider: &dyn AssetProvider,
	asset_root: &str,
) -> Vec<ParticleSprite> {
	let mut sprites = Vec::new();
	let mut textures: HashMap<&str, Option<Arc<Texture>>> = HashMap::new();

	for particle in particles {
		let Some(system) = manifest.systems.get(&particle.system_id) else {
			continue;
		};
		let anchor = match &particle.target_node_name {
			Some(name) => match find_node_by_name(nodes, name) {
				Some(node) => node.transform,
				None => continue,
			},
			None => Mat4::IDENTITY,
		};
		let particle_scale = particle.scale.unwrap_or(1.0);

		for group in &system.spawners {
			let Some(spawner) = manifest.spawners.get(&group.spawner_id) else {
				continue;
			};
			let texture_path = spawner.particle.texture.as_str();
			let texture = textures.entry(texture_path).or_insert_with(|| {
				let bytes = asset_provider
					.load_bytes(&format!("{}/{}", asset_root, texture_path))
					.ok()?;
				Texture::from_bytes(&bytes).ok().map(Arc::new)
			});
			let Some(texture) = texture.clone() else {
				continue;
			};

			let origin = Vec3::from(particle.position_offset) + Vec3::from(group.position_offset);
			spawner_sprites(
				&group.spawner_id,
				spawner,
				anchor,
				origin,
				particle_scale,
				texture,
				&mut sprites,
			);
		}
	}

	sprites
}

fn spawner_sprites(
	spawner_id: &str,
	spawner: &ParticleSpawner,
	anchor: Mat4,
	origin: Vec3,
	particle_scale: f32,
	texture: Arc<Texture>,
	sprites: &mut Vec<ParticleSprite>,
) {
	let def = &spawner.particle;
	let keys = Keyframes::new(&def.animation);
	let t = keys.peak_time();
	let initial = &def.initial_animation_frame;

	let opacity = initial.opacity.unwrap_or(1.0) * keys.value(t, |f| f.opacity).unwrap_or(1.0);
	let [r, g, b] = keys
		.rgb(t)
		.or_else(|| initial.color.as_deref().and_then(parse_hex_rgb))
		.unwrap_or([1.0; 3]);
	let anim_scale_x = keys
		.value(t, |f| f.scale.and_then(|s| s.x).map(|r| r.lerp(0.5)))
		.unwrap_or(1.0);
	let anim_scale_y = keys
		.value(t, |f| f.scale.and_then(|s| s.y).map(|r| r.lerp(0.5)))
		.unwrap_or(1.0);
	let frame_index = keys
		.step(t, |f| f.frame_index)
		.or(initial.frame_index)
		.map_or(0, |r| r.min.max(0.0) as u32);

	let (tex_w, tex_h) = texture.dimensions();
	let frame_size = def
		.frame_size
		.map_or((tex_w, tex_h), |f| (f.width, f.height));
	let columns = (tex_w / frame_size.0.max(1)).max(1);
	let frame = (
		(frame_index % columns) * frame_size.0,
		(frame_index / columns) * frame_size.1,
		frame_size.0,
		frame_size.1,
	);

	let facing = if spawner.particle_rotation_influence.as_deref() == Some("BillboardVelocity") {
		SpriteFacing::Upright
	} else {
		SpriteFacing::Camera
	};
	let initial_scale = initial.scale.unwrap_or_default();
	let one_to_one = def.scale_ratio_constraint.as_deref() == Some("OneToOne");

	let count = spawner.max_concurrent_particles.unwrap_or(1);
	let emit = spawner.emit_offset;
	let emit_radius = Vec3::new(
		emit.x.map_or(0.0, |r| r.max),
		emit.y.map_or(0.0, |r| r.max),
		emit.z.map_or(0.0, |r| r.max),
	);

	// Radial attractors keep particles orbiting at their radius, so linear lift only accumulates without them.
	let orbit_radius = spawner
		.attractors
		.iter()
		.filter(|a| a.radial_acceleration != 0.0 || a.radial_tangent_acceleration != 0.0)
		.filter_map(|a| a.radius)
		.reduce(f32::max);
	let drift = if orbit_radius.is_some() {
		Vec3::ZERO
	} else {
		let age = t / 100.0 * spawner.particle_life_span.map_or(0.0, |r| r.lerp(0.5));
		let acceleration: Vec3 = spawner
			.attractors
			.iter()
			.map(|a| Vec3::from(a.linear_acceleration))
			.sum();
		acceleration * 0.5 * age * age
	};

	for index in 0..count {
		let mut rng = Rng::new(spawner_id, index);

		// Samples inside the emit shape mostly land inside the model and get hidden, so fan particles across the
		// front of the shell (avatars face the viewer), tilted up the way the spawners' attractors lift them.
		let azimuth = std::f32::consts::PI * ((index as f32 + 0.5) / count as f32 - 0.5)
			+ (rng.next() - 0.5) * 0.4;
		let elevation = 0.35 + rng.next() * 0.35;
		let direction = Vec3::new(
			azimuth.sin() * elevation.cos(),
			elevation.sin(),
			azimuth.cos() * elevation.cos(),
		);
		let offset = match orbit_radius {
			Some(radius) => direction * radius,
			None => direction * emit_radius + drift,
		};
		let center = anchor.transform_point3((origin + offset) * UNITS_PER_BLOCK);

		let scale_x = initial_scale.x.map_or(1.0, |r| r.lerp(rng.next())) * anim_scale_x;
		let scale_y = if one_to_one {
			scale_x
		} else {
			initial_scale.y.map_or(1.0, |r| r.lerp(rng.next())) * anim_scale_y
		};

		sprites.push(ParticleSprite {
			center,
			size: Vec2::new(scale_x, scale_y) * particle_scale * UNITS_PER_BLOCK,
			facing,
			color: [r, g, b, opacity.clamp(0.0, 1.0)],
			texture: texture.clone(),
			frame,
		});
	}
}

/// Animation keyframes sorted by lifetime percentage
struct Keyframes<'a> {
	frames: Vec<(f32, &'a AnimationFrame)>,
}

impl<'a> Keyframes<'a> {
	fn new(animation: &'a HashMap<String, AnimationFrame>) -> Self {
		let mut frames: Vec<(f32, &AnimationFrame)> = animation
			.iter()
			.filter_map(|(key, frame)| Some((key.parse::<f32>().ok()?, frame)))
			.collect();
		frames.sort_by(|a, b| a.0.total_cmp(&b.0));
		Self { frames }
	}

	/// Midpoint of the first longest run of maximum opacity, as a lifetime percentage
	fn peak_time(&self) -> f32 {
		let samples: Vec<f32> = (0..=100)
			.map(|t| self.value(t as f32, |f| f.opacity).unwrap_or(1.0))
			.collect();
		let max = samples.iter().copied().fold(f32::MIN, f32::max);

		let mut best = (0usize, 0usize);
		let mut run_start = None;
		for (t, &opacity) in samples.iter().enumerate() {
			if (opacity - max).abs() <= 1e-4 {
				let start = *run_start.get_or_insert(t);
				if t - start > best.1 - best.0 {
					best = (start, t);
				}
			} else {
				run_start = None;
			}
		}
		(best.0 + best.1) as f32 / 2.0
	}

	/// Linearly interpolated value of a property, holding the first/last keyframe outside its range
	fn value(&self, t: f32, get: impl Fn(&AnimationFrame) -> Option<f32>) -> Option<f32> {
		self.interpolate(t, |f| get(f).map(|v| [v])).map(|[v]| v)
	}

	fn rgb(&self, t: f32) -> Option<[f32; 3]> {
		self.interpolate(t, |f| f.color.as_deref().and_then(parse_hex_rgb))
	}

	/// Value of the last keyframe at or before `t`, for discrete properties like sprite frames
	fn step(&self, t: f32, get: impl Fn(&AnimationFrame) -> Option<Range>) -> Option<Range> {
		self.frames
			.iter()
			.filter(|(time, _)| *time <= t)
			.filter_map(|(_, frame)| get(frame))
			.last()
	}

	fn interpolate<const N: usize>(
		&self,
		t: f32,
		get: impl Fn(&AnimationFrame) -> Option<[f32; N]>,
	) -> Option<[f32; N]> {
		let keys: Vec<(f32, [f32; N])> = self
			.frames
			.iter()
			.filter_map(|(time, frame)| Some((*time, get(frame)?)))
			.collect();
		let after = keys.iter().position(|(time, _)| *time >= t);
		match after {
			None => keys.last().map(|(_, v)| *v),
			Some(0) => keys.first().map(|(_, v)| *v),
			Some(i) => {
				let (t0, v0) = keys[i - 1];
				let (t1, v1) = keys[i];
				let k = (t - t0) / (t1 - t0);
				Some(std::array::from_fn(|c| v0[c] + (v1[c] - v0[c]) * k))
			}
		}
	}
}

fn parse_hex_rgb(hex: &str) -> Option<[f32; 3]> {
	let hex = hex.strip_prefix('#')?;
	if hex.len() != 6 {
		return None;
	}
	let channel = |i: usize| -> Option<f32> {
		Some(u8::from_str_radix(hex.get(i..i + 2)?, 16).ok()? as f32 / 255.0)
	};
	Some([channel(0)?, channel(2)?, channel(4)?])
}

/// Deterministic xorshift so a skin always renders the same particle layout
struct Rng(u32);

impl Rng {
	fn new(spawner_id: &str, index: u32) -> Self {
		// FNV-1a over the spawner id, mixed with the particle index
		let mut hash: u32 = 0x811c_9dc5;
		for byte in spawner_id.bytes().chain(index.to_le_bytes()) {
			hash = (hash ^ byte as u32).wrapping_mul(0x0100_0193);
		}
		Self(hash.max(1))
	}

	fn next(&mut self) -> f32 {
		self.0 ^= self.0 << 13;
		self.0 ^= self.0 >> 17;
		self.0 ^= self.0 << 5;
		(self.0 >> 8) as f32 / (1u32 << 24) as f32
	}
}

#[cfg(test)]
mod tests {
	use super::*;

	fn bundled_manifest() -> ParticleManifest {
		let path = concat!(
			env!("CARGO_MANIFEST_DIR"),
			"/../../assets/hytale/Particles/CosmeticParticles.json"
		);
		serde_json::from_slice(&std::fs::read(path).unwrap()).unwrap()
	}

	#[test]
	fn peak_is_middle_of_full_opacity_plateau_with_numeric_key_order() {
		let manifest = bundled_manifest();
		// Stink lines fade in until 35% and out after 80%; "100" sorts before "35" as a string.
		let stink = Keyframes::new(&manifest.spawners["Stink_Lines"].particle.animation);
		assert_eq!(stink.peak_time(), 57.5);
		let flies = Keyframes::new(&manifest.spawners["Flies"].particle.animation);
		assert_eq!(flies.peak_time(), 45.0);
	}

	#[test]
	fn stink_snapshot_uses_peak_frame_values() {
		let manifest = bundled_manifest();
		let spawner = &manifest.spawners["Stink_Lines"];
		let texture = Arc::new(Texture::from_image(image::DynamicImage::new_rgba8(32, 64)));
		let mut sprites = Vec::new();
		spawner_sprites(
			"Stink_Lines",
			spawner,
			Mat4::IDENTITY,
			Vec3::ZERO,
			1.0,
			texture,
			&mut sprites,
		);

		assert_eq!(sprites.len(), 2);
		let sprite = &sprites[0];
		assert_eq!(sprite.facing, SpriteFacing::Upright);
		assert!((sprite.color[3] - 0.932).abs() < 1e-4);
		// Colour sits between the #b6b211 start and #93872a end keys.
		assert!(sprite.color[0] < 0xb6 as f32 / 255.0 && sprite.color[0] > 0x93 as f32 / 255.0);
		// Negative Y scale mirrors the drop so its tail points up.
		assert!(sprite.size.y < 0.0);
	}
}
